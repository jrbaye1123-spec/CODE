# ── RAG CONTEXT BUILDER ──────────────────────────────────────────────────────

def build_rag_context(retrieved_chunks: list, max_tokens: int = 2000) -> str:
    """
    Build a context string from retrieved RAG chunks for injection
    into the conversation.
    """
    if not retrieved_chunks:
        return ""

    lines = ["[Retrieved from the Myosu archive:]"]
    total = 0
    for chunk in retrieved_chunks:
        text = chunk.get("text", "") if isinstance(chunk, dict) else str(chunk)
        source = chunk.get("source", "") if isinstance(chunk, dict) else ""
        if source:
            lines.append(f"\nFrom {source}:")
        lines.append(text)
        total += len(text.split())
        if total > max_tokens:
            lines.append("\n[... further passages available ...]")
            break

    return "\n".join(lines)


